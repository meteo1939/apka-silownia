const resolveTranslation = (source: unknown, parts: string[]): string | null => {
  let current: unknown = source;

  for (const part of parts) {
    if (typeof current !== 'object' || current === null) return null;
    const record = current as Record<string, unknown>;
    if (!(part in record)) return null;
    current = record[part];
  }

  return typeof current === 'string' ? current : null;
};

export const useTranslation = () => {
  const user = useAuthStore(state => state.user);
  const lang = user?.language || 'pl';

  const t = (path: string, fallback?: string): string => {
    const parts = path.split('.');
    const active = translations[lang as 'pl' | 'en'] || translations['pl'];

    return resolveTranslation(active, parts)
      ?? resolveTranslation(translations['pl'], parts)
      ?? fallback
      ?? path;
  };

  return { t, lang };
};

